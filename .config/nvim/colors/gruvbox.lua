-- colors/gruvbox.lua
-- Standalone gruvbox colorscheme.
--
-- Based on ellisonleao/gruvbox.nvim (MIT), adapted into a single file so the
-- plugin is no longer required. Dark and light palettes are selected from
-- 'background'; Neovim re-sources the active colorscheme when that option
-- changes, so `:set background=light` / `:set background=dark` switches
-- automatically.
--
-- The config below mirrors the settings that used to live in
-- plugin/colorscheme.lua.

